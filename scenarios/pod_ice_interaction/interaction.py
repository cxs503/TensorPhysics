"""Propeller-ice interaction: rotor dynamics, spectral phase and pod reaction.

The propeller is exposed to a periodic ice torque spectrum generated by blade
impacts once per revolution (blade rate ``Z n``). The shaft line is modelled as

    J d(omega)/dt = Q_motor(omega) - Q_prop(omega) - Q_ice(t, v_pod)
    m x'' + c x' + k x = (T(t) - T_mean) + F_ice,ripple(t)

with

* ``Q_prop = K_Q rho n^2 D^5`` from the BEMT open-water curve (so the
  hydrodynamic damping ``k_p = dQ_prop/domega`` is a physical quantity, not a
  fitted coefficient),
* a power-limited torque controller ``Q_motor = clip(K (omega_cmd - omega)``),
* the pod strut represented by its FEM cantilever stiffness
  ``k = 3 E I_y / H^3`` and a 2 % damping ratio,
* a two-way ice coupling: the vibratory velocity of the housing changes the
  blade-ice penetration rate and therefore modulates the ice torque
  (rate effect coefficient ``kappa``).

Linearising the rotor equation gives the analytic first-order lag used as the
acceptance reference for the phase relation between the ice torque spectrum and
the thrust/torque response:

    phi = arctan(omega_f J / (k_p + K)),   phase(dT) - phase(Q_ice) = 180 deg - phi

which is compared with the phase measured from the simulated time histories by
harmonic projection at the blade-rate frequency (:func:`verify_phase`).
"""
from __future__ import annotations

from dataclasses import dataclass
from math import atan, cos, degrees, pi, radians, sin, sqrt, tan

import numpy as np

from .propeller import OpenWaterCurve
from .structure import StrutSection


@dataclass(frozen=True)
class InteractionConfig:
    ice_torque_mean: float = 0.30e6    # N m, mean ice torque on the shaft line
    blade_duty: float = 0.18           # fraction of a revolution in blade-ice contact
    duration: float = 4.8             # s, integer number of blade-rate periods
    dt: float = 2.0e-4                # s
    controller_gain: float = 1.0e6    # N m / (rad/s)
    rotor_inertia: float = 2.1e4      # kg m^2 (propeller + motor rotor)
    pod_mass: float = 6.0e4           # kg (pod body + entrained water)
    damping_ratio: float = 0.02
    rate_coupling: float = 0.15       # d p_c / d v (ice rate effect), 1/(m/s)
    v_ref: float = 1.0                # m/s reference penetration velocity
    # True: ice contacts are locked to the instantaneous blade angle (milling);
    # False: the ice load spectrum is prescribed in time at the commanded rate,
    # which is the form used for the spectral phase verification.
    angle_locked: bool = False
    contact_radius_factor: float = 0.75  # ice torque -> force: r_c = 0.75 R

    def __post_init__(self) -> None:
        if not 0.0 < self.blade_duty <= 0.25:
            raise ValueError("blade_duty must lie in (0, 0.25] for four-bladed pods")
        if self.dt <= 0.0 or self.duration <= 0.0:
            raise ValueError("dt and duration must be positive")
        if self.ice_torque_mean < 0.0:
            raise ValueError("ice_torque_mean must be non-negative")


def ice_torque_shape(theta: np.ndarray, n_blades: int, duty: float) -> np.ndarray:
    """Normalised periodic ice torque shape (peak = 1) as a function of angle.

    Each blade is in ice contact during a fraction ``duty`` of a revolution; the
    contact pulse is smooth (``sin^2``) so that the signal has a well defined
    blade-rate fundamental and no numerical ringing.
    """
    if duty > 1.0 / n_blades:
        raise ValueError("blade_duty must not exceed 1/n_blades (no pulse overlap)")
    total = np.zeros_like(np.asarray(theta, dtype=float))
    for k in range(n_blades):
        phase = np.mod(theta - 2.0 * pi * k / n_blades, 2.0 * pi)
        inside = phase < duty * 2.0 * pi
        total = total + np.where(inside, np.sin(pi * phase / (duty * 2.0 * pi)) ** 2, 0.0)
    return total  # peak is 1 by construction when the pulses do not overlap


def simulate_interaction(
    curve: OpenWaterCurve,
    pod_spec,
    ice_case,
    config: InteractionConfig | None = None,
    *,
    v_ship: float = 8.0,
    two_way: bool = True,
    n_cmd_rpm: float | None = None,
) -> dict:
    """Time-domain simulation of the pod under the ice torque spectrum.

    Returns time histories of shaft speed, thrust, propeller torque, ice torque
    and the pod vibration state, together with derived spectral quantities.
    """
    cfg = config or InteractionConfig()
    geom = curve.geometry
    n_blades = geom.n_blades
    n_cmd = (n_cmd_rpm / 60.0) if n_cmd_rpm is not None else pod_spec.n_rated_rps
    omega_cmd = 2.0 * pi * n_cmd
    q_max = pod_spec.motor_torque_limit
    r_contact = cfg.contact_radius_factor * geom.radius
    k_strut = pod_spec.strut.lateral_stiffness
    m_pod = cfg.pod_mass
    c_pod = 2.0 * cfg.damping_ratio * sqrt(k_strut * m_pod)

    t_end = cfg.duration
    dt = cfg.dt
    n_steps = int(round(t_end / dt)) + 1
    t = np.linspace(0.0, t_end, n_steps)

    def ice_torque(theta: float, v_vib: float, t: float = 0.0) -> float:
        if not cfg.angle_locked:
            theta = omega_cmd * t
        shape = ice_torque_shape(np.array([theta]), n_blades, cfg.blade_duty)[0]
        modulation = 1.0 + (cfg.rate_coupling * v_vib / cfg.v_ref if two_way else 0.0)
        return ice_peak * shape * modulation

    t_cur = 0.0

    def derivatives(state: np.ndarray) -> np.ndarray:
        omega, theta, x, xd = state
        n = max(omega / (2.0 * pi), 1e-4)
        q_prop = curve.torque(n, v_ship)
        thrust = curve.thrust(n, v_ship)
        q_motor = cfg.controller_gain * (omega_cmd - omega)
        q_motor = float(np.clip(q_motor, -q_max, q_max))
        q_ice = ice_torque(theta, xd, t_cur)
        f_ice = q_ice / r_contact
        f_exc = (thrust - thrust_mean) + (f_ice - f_ice_mean)
        domega = (q_motor - q_prop - q_ice) / cfg.rotor_inertia
        dxdd = (f_exc - c_pod * xd - k_strut * x) / m_pod
        return np.array([domega, omega, xd, dxdd])

    # mean ice load (used only to centre the mechanical excitation)
    theta_grid = np.linspace(0.0, 2.0 * pi, 4000)
    shape = ice_torque_shape(theta_grid, n_blades, cfg.blade_duty)
    shape_mean = max(float(np.mean(shape)), 1e-9)
    ice_peak = cfg.ice_torque_mean / shape_mean
    # peak-per-blade ice torque consistent with the configured mean level
    q_ice_mean = cfg.ice_torque_mean
    f_ice_mean = q_ice_mean / r_contact
    thrust_mean = curve.thrust(n_cmd, v_ship)

    # start from the steady state under the mean ice load (avoids a start-up
    # transient that would contaminate the harmonic phase extraction)
    omega0 = omega_cmd - q_ice_mean / max(cfg.controller_gain, 1e-9)
    state = np.array([omega0, 0.0, 0.0, 0.0])
    hist = np.empty((n_steps, 8))
    n0 = max(omega0 / (2.0 * pi), 1e-4)
    hist[0] = [t[0], state[0], state[2], state[3],
               ice_torque(0.0, 0.0, 0.0), curve.thrust(n0, v_ship),
               curve.torque(n0, v_ship), ice_torque(0.0, 0.0, 0.0) / r_contact]
    for i in range(1, n_steps):
        t_cur = t[i - 1]
        k1 = derivatives(state)
        k2 = derivatives(state + 0.5 * dt * k1)
        k3 = derivatives(state + 0.5 * dt * k2)
        k4 = derivatives(state + dt * k3)
        state = state + dt / 6.0 * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
        omega, theta, x, xd = state
        n = max(omega / (2.0 * pi), 1e-4)
        q_ice = ice_torque(theta, xd, t[i])
        hist[i] = [t[i], omega, x, xd, q_ice, curve.thrust(n, v_ship),
                   curve.torque(n, v_ship), q_ice / r_contact]

    n_rps = hist[:, 1] / (2.0 * pi)
    result = {
        "t": hist[:, 0],
        "omega": hist[:, 1],
        "n_rps": n_rps,
        "n_rpm": n_rps * 60.0,
        "thrust": hist[:, 5],
        "torque_prop": hist[:, 6],
        "torque_ice": hist[:, 4],
        "ice_force": hist[:, 7],
        "pod_displacement": hist[:, 2],
        "pod_velocity": hist[:, 3],
        "v_ship": v_ship,
        "n_cmd_rps": n_cmd,
        "blade_frequency": n_blades * (float(np.mean(n_rps)) if cfg.angle_locked else n_cmd),
        "two_way": two_way,
        "rotor_inertia": cfg.rotor_inertia,
        "strut_stiffness": k_strut,
        "pod_natural_frequency": sqrt(k_strut / m_pod) / (2.0 * pi),
        "ice_torque_mean": q_ice_mean,
        "ice_torque_peak": ice_peak,
        "ice_torque_mean": cfg.ice_torque_mean,
        "blade_duty": cfg.blade_duty,
    }
    return result


def harmonic_amplitude_phase(t: np.ndarray, y: np.ndarray, frequency: float) -> tuple[float, float]:
    """Least-squares harmonic projection: ``y ~ A cos(2 pi f t + phi)``."""
    w = 2.0 * pi * frequency
    c = np.sum(y * np.exp(-1j * w * t)) * 2.0 / y.size
    return float(abs(c)), float(np.angle(c))


def verify_phase(
    result: dict,
    curve: OpenWaterCurve,
    pod_spec,
    config: InteractionConfig | None = None,
    *,
    tol_deg: float = 5.0,
    tol_amp_rel: float = 0.10,
) -> dict:
    """Compare the simulated thrust/torque phase with the analytic rotor lag.

    The analytic reference is the first-order lag of the linearised shaft line,
    ``phase(dT) - phase(Q_ice) = 180 deg - arctan(omega_f J / (k_p + K))`` with
    ``k_p = dQ_prop/domega`` taken from the BEMT curve and ``K`` the controller
    gain. The measured phase comes from harmonic projection of the simulated
    histories at the blade-rate frequency.
    """
    cfg = config or InteractionConfig()
    t = result["t"]
    f_b = result["blade_frequency"]
    n_mean = float(np.mean(result["n_rps"]))
    w = 2.0 * pi * f_b
    k_p = curve.torque_gradient(n_mean, result["v_ship"]) / (2.0 * pi)
    k_t = curve.thrust_gradient(n_mean, result["v_ship"]) / (2.0 * pi)
    # When the motor torque is at its limit the controller cannot react to the
    # ripple: the effective damping is the hydrodynamic one only.
    q_rating = pod_spec.motor_torque_limit
    mean_torque_prop = float(np.mean(result["torque_prop"]))
    mean_ice_torque = float(np.mean(result["torque_ice"]))
    # The check is made with the peak combination, because intermittent torque
    # limit clipping (ice torque peak on top of the propeller torque) already
    # invalidates the linear reference even if the mean is below the limit.
    peak_saturation = (max(result["torque_prop"] + result["torque_ice"])
                       >= 0.999 * q_rating)
    saturated = (mean_torque_prop + mean_ice_torque) >= 0.999 * q_rating
    c_eff = k_p if saturated else k_p + cfg.controller_gain
    linear_regime = not peak_saturation
    inert = cfg.rotor_inertia
    phi_analytic = atan(w * inert / c_eff)
    phase_diff_analytic = 180.0 - degrees(phi_analytic)

    amp_ice, phase_ice = harmonic_amplitude_phase(t, result["torque_ice"], f_b)
    amp_t, phase_t = harmonic_amplitude_phase(t, result["thrust"] - np.mean(result["thrust"]), f_b)
    amp_q, phase_q = harmonic_amplitude_phase(t, result["torque_prop"] - np.mean(result["torque_prop"]), f_b)

    def wrap(x: float) -> float:
        return (x + 180.0) % 360.0 - 180.0

    phase_diff_measured = wrap(degrees(phase_t - phase_ice))
    phase_error = abs(wrap(phase_diff_measured - phase_diff_analytic))

    amp_ratio_analytic = k_t / sqrt(c_eff ** 2 + (w * inert) ** 2)
    amp_ratio_measured = amp_t / amp_ice
    amp_error_rel = abs(amp_ratio_measured - amp_ratio_analytic) / amp_ratio_analytic

    return {
        "blade_frequency": f_b,
        "phase_diff_analytic_deg": phase_diff_analytic,
        "phase_diff_measured_deg": phase_diff_measured,
        "phase_error_deg": phase_error,
        "amp_thrust": amp_t,
        "amp_ice_torque": amp_ice,
        "amp_torque_prop": amp_q,
        "amp_ratio_analytic": amp_ratio_analytic,
        "amp_ratio_measured": amp_ratio_measured,
        "amp_error_rel": amp_error_rel,
        "hydrodynamic_damping_kp": k_p,
        "controller_gain": cfg.controller_gain,
        "motor_saturated": bool(saturated),
        "peak_torque_clipping": bool(peak_saturation),
        "linear_regime": bool(linear_regime),
        "effective_damping": c_eff,
        "phase_ok": phase_error <= tol_deg,
        "amplitude_ok": amp_error_rel <= tol_amp_rel,
        "passed": phase_error <= tol_deg and amp_error_rel <= tol_amp_rel,
    }


def compare_coupling(result_one_way: dict, result_two_way: dict) -> dict:
    """Quantify the reaction of the pod vibration on the ice load.

    The two-way run modulates the ice torque with the housing vibratory velocity;
    the amplitude difference against the one-way run measures the strength of
    that back-coupling.
    """
    f_b = result_two_way["blade_frequency"]
    a_ice_1, _ = harmonic_amplitude_phase(result_one_way["t"], result_one_way["torque_ice"], f_b)
    a_ice_2, _ = harmonic_amplitude_phase(result_two_way["t"], result_two_way["torque_ice"], f_b)
    a_t_1, _ = harmonic_amplitude_phase(
        result_one_way["t"], result_one_way["thrust"] - np.mean(result_one_way["thrust"]), f_b)
    a_t_2, _ = harmonic_amplitude_phase(
        result_two_way["t"], result_two_way["thrust"] - np.mean(result_two_way["thrust"]), f_b)
    return {
        "ice_torque_amp_one_way": a_ice_1,
        "ice_torque_amp_two_way": a_ice_2,
        "ice_torque_change_rel": abs(a_ice_2 - a_ice_1) / a_ice_1,
        "thrust_amp_one_way": a_t_1,
        "thrust_amp_two_way": a_t_2,
        "thrust_change_rel": abs(a_t_2 - a_t_1) / a_t_1,
        "pod_velocity_rms": float(np.sqrt(np.mean(result_two_way["pod_velocity"] ** 2))),
        "pod_displacement_rms": float(np.sqrt(np.mean(result_two_way["pod_displacement"] ** 2))),
        "min_rpm_two_way": float(np.min(result_two_way["n_rpm"])),
        "mean_rpm_two_way": float(np.mean(result_two_way["n_rpm"])),
        "mean_thrust_two_way": float(np.mean(result_two_way["thrust"])),
        "mean_ice_force_two_way": float(np.mean(result_two_way["ice_force"])),
    }