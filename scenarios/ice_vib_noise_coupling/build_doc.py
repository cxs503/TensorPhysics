        + " of the\ninput work, i.e. three orders of magnitude below the quadrature error of the\n"
        "ledger, which is why the closure residual must be attributed carefully:\n\n"
        f"* `residual_with_ode_damping` = {_g(c3['residual_with_ode_damping_j'], 4)} J "
        f"({_g(c3['residual_with_ode_damping_over_work'])} of W_in) is the pure\n"
        "  quadrature/integration error of the energy integrals;\n"
        f"* the reported `residual` = {_g(c3['residual_j'], 4)} J "
        f"({_g(c3['residual_over_work'])} of W_in) additionally contains the difference\n"
