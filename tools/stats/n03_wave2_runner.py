def gaussian_truth_gen(rng, n_samples, error_level):
    """Locations-scale truth generator.

    level 0: i.i.d. normal, no structure error
    level 1: 15 % contamination with a shifted component (model-structure error
             the pipeline does not know about)
    level 2: contamination + heteroscedastic noise (sigma grows with index)
    """
    true_theta = 3.0
    if error_level == 0:
        data = rng.normal(true_theta, 1.0, size=n_samples)
    elif error_level == 1:
        n_bad = max(1, int(round(0.15 * n_samples)))
        clean = rng.normal(true_theta, 1.0, size=n_samples - n_bad)
        dirty = rng.normal(true_theta + 2.4, 1.0, size=n_bad)
        data = np.concatenate([clean, dirty])
        rng.shuffle(data)
    elif error_level == 2:
        n_bad = max(1, int(round(0.15 * n_samples)))
        idx = np.arange(n_samples)
        sigmas = 1.0 + 0.02 * idx
        data = rng.normal(true_theta, sigmas)
        data[:n_bad] += 2.4
    else:
        raise ValueError(f"unknown error_level {error_level}")
    return data, true_theta


def t_interval_estimator(data):
    """Student-t interval for the mean — the well-calibrated reference pipeline."""
    x = np.asarray(data, dtype=float)
    n = len(x)
    mean = float(x.mean())
    se = float(x.std(ddof=1) / np.sqrt(n))
    # two-sided 95 % t quantile, without SciPy to keep the runner dependency-light
    from scipy import stats as st
    tq = float(st.t.ppf(0.975, df=n - 1))
    return mean, mean - tq * se, mean + tq * se


