def run_reference(n_rep: int, seed: int = 42) -> dict:
    audit = CoverageAudit(gaussian_truth_gen, t_interval_estimator,
                          n_replications=n_rep, n_samples=50, seed=seed,
                          estimator_name="t_interval_mean_n50")
    return audit.run(error_levels=(0, 1, 2)).as_dict()


def run_controls(n_rep: int, nominal_width: float, seed: int = 42) -> dict:
    half = CoverageAudit(gaussian_truth_gen, scaled_estimator(t_interval_estimator, 0.5),
                         n_replications=n_rep, n_samples=50, seed=seed,
                         estimator_name="t_interval_mean_n50_halfwidth",
                         nominal_width=nominal_width).run(error_levels=(0,)).as_dict()
    wide = CoverageAudit(gaussian_truth_gen, scaled_estimator(t_interval_estimator, 3.0),
                         n_replications=n_rep, n_samples=50, seed=seed,
                         estimator_name="t_interval_mean_n50_width_x3",
                         nominal_width=nominal_width).run(error_levels=(0,)).as_dict()
    return {"half_width": half, "width_x3": wide}


def run_detection(n_trials: int, n_rep: int, seed: int = 42) -> dict:
    return detection_rate(gaussian_truth_gen, t_interval_estimator, error_level=1,
                          n_trials=n_trials, n_replications=n_rep, n_samples=50,
                          seed=seed).as_dict()


def run_stopping(coverage_observed: float) -> dict:
    table = coverage_resolution_table(coverage_observed)
    widths = [r["half_width"] for r in table]
    monotone = all(b < a for a, b in zip(widths, widths[1:]))
    n_min_case = solve_n_min_from_resolution(coverage_observed, 0.02)
    n_min_worst = solve_n_min(0.5, 0.02)
    hw500 = next(r["half_width"] for r in table if r["n"] == 500)
    return {
        "coverage_used": coverage_observed,
        "table": table,
        "monotone_narrowing": bool(monotone),
        "n_min_case_specific": int(n_min_case),
        "n_min_worst_case_p50": int(n_min_worst),
        "speedup_vs_worst_case": float(n_min_worst / n_min_case),
        "resolved_half_width_at_n500": float(hw500),
    }


def run_case_sweep(n_grid, n_rep: int, seed: int = 42) -> dict:
    """Case-A sample-size sweep: at which n does a 95 % interval calibrate?"""
    rows = []
    for n in n_grid:
        for label, factory in (("percentile_bootstrap_B1000", make_weibull_estimator),
                               ("mle_profile", make_weibull_mle_profile_estimator)):
            if label == "mle_profile":
                est = factory()
            else:
                est = factory(B=1000, seed=2024)
            res = CoverageAudit(weibull_truth_gen, est, n_replications=n_rep,
                                n_samples=int(n), seed=seed,
                                estimator_name=f"caseA_{label}_n{int(n)}"
                                ).run(error_levels=(0,)).as_dict()
            lv = res["levels"][0]
            rows.append({"estimator": label, "n_samples": int(n),
                         "n_replications": n_rep,
                         "coverage": lv["coverage"],
                         "mean_ci_width": lv["mean_ci_width"],
                         "bias": lv["mean_theta_hat"] - res["true_theta"],
                         "spec_verdict": lv["spec_verdict"]})
    return {"rows": rows}


