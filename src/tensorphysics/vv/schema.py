def schema_path() -> Path:
    return Path(__file__).resolve().parent / "schemas" / "vv_benchmark.schema.json"


def write_schema(path: str | Path | None = None) -> Path:
    """Write :data:`VV_BENCHMARK_SCHEMA` to disk (default: the shipped location)."""
    target = Path(path) if path is not None else schema_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(VV_BENCHMARK_SCHEMA, indent=2) + "\n", encoding="utf-8")
    return target