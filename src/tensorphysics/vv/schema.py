"""The cross-repository benchmark contract consumed by the V&V gate.

One JSON document, one shape, five repositories.  The contract is deliberately
small -- a fixed-length observable study plus optional feature scales and an
optional validation block -- because every field beyond that belongs to the
solver's own dialect (which the adapters translate, see
:mod:`tensorphysics.vv.adapters`).

.. code-block:: json

    {
      "schema": "ship-performance.vv-benchmark/1",
      "quantity": "total_resistance",
      "unit": "kN",
      "levels": [
        {"panels": 1200, "total_resistance": 412.5, "sigma": 0.8},
        {"panels": 2400, "total_resistance": 405.1, "sigma": 0.4},
        {"panels": 4800, "total_resistance": 402.2, "sigma": 0.2}
      ],
      "features": [{"name": "boundary_layer", "delta": 0.004, "unit": "m"}],
      "validation": {"f_sim": 402.2, "f_exp": 398.0, "u_input": 1.5, "u_ref": 2.0}
    }

Rules enforced by :func:`check_benchmark` (all dependency-free):

* ``schema`` and ``quantity`` are non-empty strings;
* ``levels`` holds at least two mappings, each with a positive grid length
  (``h``/``dx``/``dt``/``panel_size``/...) **or** a positive grid count
  (``panels``/``resolution``/...), plus a finite observable, plus optional
  ``sigma >= 0``;
* grid spacings derived from the levels are strictly decreasing once counts are
  converted with ``h = 1/count`` -- the gate cannot infer an order otherwise;
* ``features`` entries carry a name and a positive ``delta``;
* ``validation`` carries finite ``f_sim``/``f_exp`` and non-negative
  ``u_input``/``u_ref``/``u_num``.

The schema file shipped next to this module
(``schemas/vv_benchmark.schema.json``) is generated by :func:`write_schema` so
the contract and the code cannot drift.
"""
