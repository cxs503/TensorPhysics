"""Wave height decay with distance from ship track.

This module implements the classical wave height decay laws for ship wakes:

1. **Deep water**: H ∝ 1/√r (geometric spreading in 2D)
2. **Shallow water**: H ∝ 1/r (geometric spreading in 1D, cylindrical)

The transition between regimes occurs at depth h ≈ λ/(2π), where λ is the
characteristic wavelength. In practice, the shallow water limit applies when
h < λ/20 (the "shallow water" criterion from linear wave theory).

The decay also depends on the angle from the ship track:
- Transverse waves (θ ≈ 0°): slower decay, more persistent
- Divergent waves (θ ≈ 70°): faster decay due to geometric spreading

References:
    - Havelock, T.H. (1908). "The wave pattern of a ship in uniform motion".
      Proc. Roy. Soc. A.
    - Noblesse, F. (1981). "Waves generated by a ship in uniform motion".
      J. Ship Res. 25(4), 227-237.
    - PIANC (2003). "Guidelines for Managing Wake Wash from High-Speed Vessels".
      Report of MarCom Working Group 38.
"""

from __future__ import annotations

import math
from typing import Tuple, Optional


class WaveDecayError(Exception):
    """Exception raised for wave height decay errors."""
    pass


def deep_water_decay(
    reference_height: float,
    reference_distance: float,
    target_distance: float
) -> float:
    """Compute wave height at target distance using deep water decay law.
    
    In deep water, wave energy spreads in 2D (circular wave fronts), so
    the wave height decays as H ∝ 1/√r:
        H(r) = H_ref * sqrt(r_ref / r)
    
    Args:
        reference_height: Wave height at reference distance [m].
        reference_distance: Reference distance from ship [m].
        target_distance: Target distance from ship [m].
    
    Returns:
        float: Wave height at target distance [m].
    
    Raises:
        WaveDecayError: If distances are non-positive.
    
    Example:
        >>> H = deep_water_decay(1.0, 100.0, 400.0)
        >>> abs(H - 0.5) < 0.01  # H ∝ 1/√r, so H(400) = H(100) * sqrt(100/400) = 0.5
        True
    """
    if reference_distance <= 0:
        raise WaveDecayError(f"Reference distance must be positive, got {reference_distance}")
    if target_distance <= 0:
        raise WaveDecayError(f"Target distance must be positive, got {target_distance}")
    if reference_height < 0:
        raise WaveDecayError(f"Reference height must be non-negative, got {reference_height}")
    
    # H(r) = H_ref * sqrt(r_ref / r)
    height = reference_height * math.sqrt(reference_distance / target_distance)
    
    return height


def shallow_water_decay(
    reference_height: float,
    reference_distance: float,
    target_distance: float
) -> float:
    """Compute wave height at target distance using shallow water decay law.
    
    In shallow water, wave energy spreads in 1D (plane wave fronts), so
    the wave height decays as H ∝ 1/r:
        H(r) = H_ref * (r_ref / r)
    
    Args:
        reference_height: Wave height at reference distance [m].
        reference_distance: Reference distance from ship [m].
        target_distance: Target distance from ship [m].
    
    Returns:
        float: Wave height at target distance [m].
    
    Raises:
        WaveDecayError: If distances are non-positive.
    
    Example:
        >>> H = shallow_water_decay(1.0, 100.0, 400.0)
        >>> abs(H - 0.25) < 0.01  # H ∝ 1/r, so H(400) = H(100) * 100/400 = 0.25
        True
    """
    if reference_distance <= 0:
        raise WaveDecayError(f"Reference distance must be positive, got {reference_distance}")
    if target_distance <= 0:
        raise WaveDecayError(f"Target distance must be positive, got {target_distance}")
    if reference_height < 0:
        raise WaveDecayError(f"Reference height must be non-negative, got {reference_height}")
    
    # H(r) = H_ref * (r_ref / r)
    height = reference_height * (reference_distance / target_distance)
    
    return height


def transition_depth(wavelength: float) -> float:
    """Compute the water depth at which transition from deep to shallow occurs.
    
    The transition depth is approximately h_t ≈ λ/(2π), where λ is the
    characteristic wavelength. Below this depth, the wave "feels" the bottom.
    
    A more practical criterion is h < λ/20 for "shallow water" behavior.
    
    Args:
        wavelength: Characteristic wavelength [m].
    
    Returns:
        float: Transition depth [m] (λ/(2π)).
    
    Example:
        >>> h_t = transition_depth(10.0)
        >>> abs(h_t - 10.0/(2*math.pi)) < 0.01
        True
    """
    if wavelength <= 0:
        raise WaveDecayError(f"Wavelength must be positive, got {wavelength}")
    
    return wavelength / (2.0 * math.pi)


def shallow_water_criterion(wavelength: float) -> float:
    """Compute the depth below which shallow water approximation applies.
    
    The shallow water criterion is h < λ/20, where λ is the wavelength.
    
    Args:
        wavelength: Characteristic wavelength [m].
    
    Returns:
        float: Maximum depth for shallow water behavior [m].
    
    Example:
        >>> h_shallow = shallow_water_criterion(10.0)
        >>> abs(h_shallow - 0.5) < 0.01
        True
    """
    if wavelength <= 0:
        raise WaveDecayError(f"Wavelength must be positive, got {wavelength}")
    
    return wavelength / 20.0


def wave_height_with_depth(
    reference_height: float,
    reference_distance: float,
    target_distance: float,
    water_depth: float,
    wavelength: float
) -> float:
    """Compute wave height accounting for depth-dependent decay.
    
    This function selects the appropriate decay law based on the ratio
    of water depth to wavelength:
    - h > λ/2: deep water decay (H ∝ 1/√r)
    - h < λ/20: shallow water decay (H ∝ 1/r)
    - λ/20 < h < λ/2: interpolated (linear blend)
    
    Args:
        reference_height: Wave height at reference distance [m].
        reference_distance: Reference distance from ship [m].
        target_distance: Target distance from ship [m].
        water_depth: Water depth [m].
        wavelength: Characteristic wavelength [m].
    
    Returns:
        float: Wave height at target distance [m].
    
    Raises:
        WaveDecayError: If parameters are invalid.
    
    Example:
        >>> H = wave_height_with_depth(1.0, 100.0, 400.0, 50.0, 10.0)
        >>> H > 0
        True
    """
    if water_depth <= 0:
        raise WaveDecayError(f"Water depth must be positive, got {water_depth}")
    if wavelength <= 0:
        raise WaveDecayError(f"Wavelength must be positive, got {wavelength}")
    
    h_deep = transition_depth(wavelength)
    h_shallow = shallow_water_criterion(wavelength)
    
    H_deep = deep_water_decay(reference_height, reference_distance, target_distance)
    H_shallow = shallow_water_decay(reference_height, reference_distance, target_distance)
    
    if water_depth >= h_deep:
        # Deep water
        return H_deep
    elif water_depth <= h_shallow:
        # Shallow water
        return H_shallow
    else:
        # Transition zone: linear interpolation
        # weight = 0 at h = h_deep (pure deep water)
        # weight = 1 at h = h_shallow (pure shallow water)
        weight = (h_deep - water_depth) / (h_deep - h_shallow)
        return H_deep * (1.0 - weight) + H_shallow * weight


def decay_profile(
    reference_height: float,
    reference_distance: float,
    distances: list,
    water_depth: Optional[float] = None,
    wavelength: Optional[float] = None
) -> list:
    """Compute wave height decay profile over a range of distances.
    
    Args:
        reference_height: Wave height at reference distance [m].
        reference_distance: Reference distance from ship [m].
        distances: List of target distances [m].
        water_depth: Water depth [m]. If None, uses deep water decay.
        wavelength: Characteristic wavelength [m]. Required if water_depth given.
    
    Returns:
        list: Wave heights at each distance [m].
    
    Example:
        >>> distances = [100, 200, 400, 800]
        >>> heights = decay_profile(1.0, 100.0, distances)
        >>> len(heights) == 4
        True
    """
    if water_depth is not None and wavelength is None:
        raise WaveDecayError("Wavelength required when water_depth is specified")
    
    heights = []
    for r in distances:
        if water_depth is not None and wavelength is not None:
            H = wave_height_with_depth(
                reference_height, reference_distance, r,
                water_depth, wavelength
            )
        else:
            H = deep_water_decay(reference_height, reference_distance, r)
        heights.append(H)
    
    return heights


def energy_flux_conservation(
    wave_height: float,
    wavelength: float,
    water_depth: Optional[float] = None
) -> float:
    """Compute wave energy flux per unit crest length.
    
    The energy flux (power per unit crest length) is:
        P = (1/8) * ρ * g * H² * c_g
    
    where c_g is the group velocity:
    - Deep water: c_g = c/2 = sqrt(g λ / (4π))
    - Shallow water: c_g = sqrt(g h)
    
    Args:
        wave_height: Wave height [m].
        wavelength: Wavelength [m].
        water_depth: Water depth [m]. If None, assumes deep water.
    
    Returns:
        float: Energy flux per unit crest length [W/m].
    
    Example:
        >>> P = energy_flux_conservation(1.0, 10.0)
        >>> P > 0
        True
    """
    rho = 1025.0  # seawater density [kg/m³]
    g = 9.81  # m/s²
    
    if water_depth is None or water_depth > transition_depth(wavelength):
        # Deep water: c_g = c/2
        c = math.sqrt(g * wavelength / (2.0 * math.pi))
        c_g = c / 2.0
    else:
        # Shallow water: c_g = sqrt(g h)
        c_g = math.sqrt(g * water_depth)
    
    # Energy flux: P = (1/8) * ρ * g * H² * c_g
    P = (1.0 / 8.0) * rho * g * wave_height**2 * c_g
    
    return P


