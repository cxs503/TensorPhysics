"""Polar ship steel material model for grounding damage assessment.

The module wraps the vectorised plane-stress J2 return mapping already
verified in :mod:`tensorphysics.plate_buckling.core` and adds the material
data and the *failure* description needed by the grounding chain:

* bilinear isotropic hardening (``E``, ``nu``, ``sigma_y``, ``E_t``);
* a strain-based tearing criterion ``eps_pl >= eps_f`` (the criterion of the
  campaign node: a panel element is deleted / declared torn once its
  accumulated equivalent plastic strain reaches the material failure strain);
* a one-dimensional reference integration (uniaxial tension) used for
  verification.

All quantities are SI (Pa, m, -).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict

import numpy as np

from ..plate_buckling.core import BilinearMaterial, plane_stress_return_map

__all__ = [
    "SteelGrade",
    "POLAR_NV_F",
    "POLAR_NV_D",
    "MILD_STEEL",
    "layer_strain",
    "uniaxial_curve",
    "plane_stress_return_map",
    "BilinearMaterial",
]


@dataclass(frozen=True)
class SteelGrade:
    """Bilinear isotropic-hardening steel with a strain-based failure limit.

    Parameters
    ----------
    name:
        Grade label (documentation / provenance only).
    E, nu, sigma_y, E_t:
        Elastic modulus, Poisson ratio, yield stress and hardening modulus.
    eps_f:
        Equivalent plastic strain at fracture (tearing).  For polar-grade
        structural steel tested at low temperature the total strain at fracture
        is > 0.20; because the elastic part is recovered, the *plastic* failure
        strain used here is 0.18 (documented limitation: no triaxiality /
        mesh-size dependence).
    """

    name: str
    E: float = 2.06e11
    nu: float = 0.3
    sigma_y: float = 3.55e8
    E_t: float = 1.0e9
    eps_f: float = 0.18

    # ------------------------------------------------------------------ props
    @property
    def bilinear(self) -> BilinearMaterial:
        return BilinearMaterial(E=self.E, nu=self.nu, sigma_y=self.sigma_y, E_t=self.E_t)

    @property
    def yield_strain(self) -> float:
        return self.sigma_y / self.E

    @property
    def plastic_modulus(self) -> float:
        """Uniaxial plastic (hardening) modulus ``H = E E_t / (E - E_t)``."""
        return self.bilinear.plastic_modulus

    def as_dict(self) -> Dict[str, float]:
        return {
            "name": self.name,
            "E": self.E,
            "nu": self.nu,
            "sigma_y": self.sigma_y,
            "E_t": self.E_t,
            "eps_f": self.eps_f,
        }


#: Polar-class hull steel (NV/FH36 type): sigma_y = 355 MPa, low-temperature
#: ductile, hardening modulus 1 GPa (E/206).
POLAR_NV_F = SteelGrade(name="NV-FH36", sigma_y=3.55e8, E_t=1.0e9, eps_f=0.18)

#: Slightly leaner polar grade (NV/DH36) used for sensitivity studies.
POLAR_NV_D = SteelGrade(name="NV-DH36", sigma_y=3.55e8, E_t=1.0e9, eps_f=0.15)

#: Reference mild steel (benchmark material).
MILD_STEEL = SteelGrade(name="mild-steel", sigma_y=2.35e8, E_t=1.0e9, eps_f=0.20)


def layer_strain(eps_m: np.ndarray, kappa: np.ndarray, z: float) -> np.ndarray:
    """Total strain at through-thickness coordinate ``z`` (von Karman kinematics).

    Parameters
    ----------
    eps_m, kappa:
        Mid-surface strain and curvature arrays of shape ``(3, ...)`` holding
        ``(xx, yy, xy)`` components; the shear component is *engineering*
        shear (``gamma_xy``).
    z:
        Through-thickness coordinate measured from the mid-surface (m).

    Returns
    -------
    ndarray of shape ``(3, ...)``: total strain at ``z``.
    """
    return eps_m + z * kappa


def uniaxial_curve(grade: SteelGrade, eps_max: float, n: int = 200):
    """Reference uniaxial tension curve (bilinear, isotropic hardening).

    The curve is generated by the *same* plane-stress return mapping used inside
    the panel solver: at every strain increment the lateral strain is solved
    with Brent's method so that the lateral stress vanishes (uniaxial *stress*
    state), which is the correct constraint in the plastic range.  Agreement
    with the analytic bilinear law is therefore a genuine check of the return
    mapping.

    Returns
    -------
    (eps, sigma, eps_pl) : tuple of ndarrays
    """
    from scipy.optimize import brentq

    mat = grade.bilinear
    n = int(max(n, 2))
    eps_hist = np.linspace(0.0, eps_max, n)
    eps_p = np.zeros((1, 3))
    alpha = np.zeros(1)
    sigma_out = np.zeros(n)
    eps_pl_out = np.zeros(n)

    def sig_matrix(eyy: float, exx: float):
        return plane_stress_return_map(np.array([[exx, eyy, 0.0]]), eps_p, alpha, mat)

    eyy = -grade.nu * eps_hist[0]
    for i, e in enumerate(eps_hist):
        # secant iteration on the lateral strain for the uniaxial stress state
        for _ in range(40):
            sig, _c, _ep, _al = sig_matrix(eyy, e)
            f = float(sig[0, 1])
            if abs(f) < 1e-6 * grade.sigma_y:
                break
            h = 1e-7
            sig2, _c2, _ep2, _al2 = sig_matrix(eyy + h, e)
            df = (float(sig2[0, 1]) - f) / h
            if abs(df) < 1e-12:
                break
            eyy -= np.clip(f / df, -1e-3, 1e-3)
        strain = np.array([[e, eyy, 0.0]])
        sig, _C, eps_p, alpha = plane_stress_return_map(strain, eps_p, alpha, mat)
        sigma_out[i] = sig[0, 0]
        eps_pl_out[i] = alpha[0]
    return eps_hist, sigma_out, eps_pl_out


def bilinear_reference(grade: SteelGrade, eps: np.ndarray):
    """Analytic bilinear uniaxial stress for total strain ``eps`` (small strain)."""
    sy = grade.sigma_y
    E = grade.E
    Et = grade.E_t
    eps_y = sy / E
    eps = np.asarray(eps, dtype=float)
    elastic = E * eps
    plastic = sy + Et * (eps - eps_y)
    return np.where(np.abs(eps) <= eps_y, elastic, np.sign(eps) * np.abs(plastic))