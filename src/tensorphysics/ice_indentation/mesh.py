"""Graded structured Hex8 meshes for indentation problems.

Indentation has a strong scale separation: the contact patch is a few
millimetres wide while the far field must stay elastic.  A uniform mesh that
resolves the contact patch in a half-space-sized block is prohibitive in a
pure-Python assembly, so this module provides a *power-graded* structured
block: node coordinates follow ``s = (i/n)**p`` along an axis, which clusters
nodes towards ``cluster="min"`` or ``cluster="max"``.

The mesh family used by the acceptance study is generated by keeping the
grading exponent ``p`` fixed and refining ``n`` -- a consistent refinement
family for the contact patch (the near-contact spacing scales as ``L / n**p``)
with the same 8-node trilinear Hex8 topology as
:mod:`tensorphysics.solid_fem.mesh`, so the element/element-kinematics code is
reused unchanged.
"""

from __future__ import annotations

import numpy as np

from ..solid_fem.mesh import SolidMesh

__all__ = [
    "graded_axis",
    "graded_box_mesh",
    "quarter_block_mesh",
    "face_nodes",
    "surface_nodal_areas",
]


def graded_axis(
    n: int, length: float, power: float = 2.0, cluster: str = "min",
    origin: float = 0.0,
) -> np.ndarray:
    """``n + 1`` axis coordinates in ``[origin, origin + length]``.

    ``power > 1`` clusters towards ``cluster`` (``"min"`` or ``"max"``);
    ``power == 1`` gives a uniform axis.
    """
    n = int(n)
    if n < 1:
        raise ValueError("n must be >= 1")
    if power <= 0.0:
        raise ValueError("power must be positive")
    t = np.linspace(0.0, 1.0, n + 1)
    if cluster == "min":
        s = t ** power
    elif cluster == "max":
        s = 1.0 - (1.0 - t) ** power
    else:
        raise ValueError(f"cluster must be 'min' or 'max', got {cluster!r}")
    axis = origin + length * s
    axis[0], axis[-1] = origin, origin + length
    return axis


def _grid_connectivity(dims) -> np.ndarray:
    nx, ny, nz = (int(d) for d in dims)

    def nid(i: int, j: int, k: int) -> int:
        return (i * (ny + 1) + j) * (nz + 1) + k

    conn = []
    for i in range(nx):
        for j in range(ny):
            for k in range(nz):
                conn.append([
                    nid(i, j, k), nid(i + 1, j, k), nid(i + 1, j + 1, k),
                    nid(i, j + 1, k), nid(i, j, k + 1), nid(i + 1, j, k + 1),
                    nid(i + 1, j + 1, k + 1), nid(i, j + 1, k + 1),
                ])
    return np.array(conn, dtype=int)


def graded_box_mesh(
    dims=(8, 8, 4),
    lengths=(10.0, 10.0, 5.0),
    powers=(2.0, 2.0, 2.0),
    clusters=("min", "min", "max"),
    origin=(0.0, 0.0, 0.0),
    element: str = "hex8",
) -> SolidMesh:
    """Structured Hex8 block with per-axis power grading."""
    if str(element).lower() != "hex8":
        raise ValueError("graded_box_mesh currently supports hex8 only")
    axes = [
        graded_axis(dims[d], lengths[d], powers[d], clusters[d], origin[d])
        for d in range(3)
    ]
    X, Y, Z = np.meshgrid(axes[0], axes[1], axes[2], indexing="ij")
    nodes = np.column_stack([X.ravel(), Y.ravel(), Z.ravel()])
    return SolidMesh(element="hex8", nodes=nodes,
                     connectivity=_grid_connectivity(dims))


def quarter_block_mesh(
    half_width: float,
    height: float,
    dims=(12, 12, 6),
    power: float = 2.0,
    vertical_power: float = 1.6,
) -> SolidMesh:
    """Quarter of an ice block, graded towards the contact point at the origin.

    The block occupies ``x, y in [0, half_width]``, ``z in [0, height]`` and is
    meant to be used with symmetry planes ``x = 0`` and ``y = 0`` and the
    contact patch centred on ``(0, 0, height)``.  Nodes cluster towards
    ``x = y = 0`` (the contact centre) and towards the top surface ``z =
    height``, which is where the indentation front is.
    """
    return graded_box_mesh(
        dims=dims,
        lengths=(half_width, half_width, height),
        powers=(power, power, vertical_power),
        clusters=("min", "min", "max"),
    )


def face_nodes(mesh: SolidMesh, axis: int, value: float, tol: float = 1e-9) -> np.ndarray:
    """Ids of the nodes whose coordinate ``axis`` equals ``value``."""
    mask = np.abs(mesh.nodes[:, axis] - value) <= tol
    return np.nonzero(mask)[0]


def surface_nodal_areas(
    mesh: SolidMesh, axis: int, value: float, tol: float = 1e-9
) -> tuple[np.ndarray, np.ndarray, float]:
    """Lumped areas of the nodes on a face, plus the face area.

    Returns ``(node_ids, areas, total_area)``.  Each surface quad of the Hex8
    mesh contributes a quarter of its area to each of its four nodes.
    """
    node_ids = face_nodes(mesh, axis, value, tol)
    areas = {int(n): 0.0 for n in node_ids}
    faces = []
    u, v = [d for d in range(3) if d != axis]
    for e in range(mesh.n_elem):
        el = mesh.connectivity[e]
        on_face = [int(n) for n in el if abs(mesh.nodes[n, axis] - value) <= tol]
        if len(on_face) != 4:
            continue
        # order the four nodes as a loop around the *quad centroid* (sorting
        # about the global origin would scramble quads away from the axis)
        pts = mesh.nodes[np.asarray(on_face)]
        cx, cy = pts[:, u].mean(), pts[:, v].mean()
        quad = np.asarray(sorted(
            on_face,
            key=lambda n: np.arctan2(mesh.nodes[n, v] - cy, mesh.nodes[n, u] - cx),
        ))
        p = mesh.nodes[quad]
        # split the quad into two triangles (convex, planar surface quad)
        a1 = 0.5 * np.linalg.norm(np.cross(p[1] - p[0], p[2] - p[0]))
        a2 = 0.5 * np.linalg.norm(np.cross(p[2] - p[0], p[3] - p[0]))
        area = float(a1 + a2)
        faces.append(area)
        for n in quad:
            areas[int(n)] += 0.25 * area
    return (node_ids,
            np.array([areas[int(n)] for n in node_ids]),
            float(np.sum(faces)))