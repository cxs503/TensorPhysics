"""Regime map generation: four-zone classification for cyclic ice pressure.

Zones:
1. Elastic shakedown: purely elastic response, no permanent deformation
2. Plastic shakedown: initial plasticity, then stabilizes
3. Ratcheting: permanent deformation accumulates each cycle
4. Alternating plasticity: plastic strain oscillates without net accumulation

Coordinates:
- x-axis: pressure amplitude (normalized by yield pressure)
- y-axis: number of cycles (log scale) or load ratio R

The map is generated by running incremental cyclic analyses at grid points
and classifying the response regime.
"""

import numpy as np
from dataclasses import dataclass
from typing import Tuple, List, Dict, Optional
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.colors as mcolors
import io
import base64

from .incremental_cyclic import (
    KinematicHardening1D, run_cyclic_analysis, classify_regime,
    CyclicHistory
)
from .frame_strip import BeamStrip, PlateStrip
from .plastic_section import RectangularSection, EPPMaterial
from .shakedown_melan import MelanShakedownBeam


# Regime colors
REGIME_COLORS = {
    "elastic_shakedown": "#4CAF50",      # green
    "plastic_shakedown": "#2196F3",       # blue
    "ratcheting": "#F44336",              # red
    "alternating_plasticity": "#FF9800",  # orange
    "unknown": "#9E9E9E",                 # gray
}

REGIME_LABELS = {
    "elastic_shakedown": "Elastic\nShakedown",
    "plastic_shakedown": "Plastic\nShakedown",
    "ratcheting": "Ratcheting",
    "alternating_plasticity": "Alternating\nPlasticity",
    "unknown": "Unknown",
}


@dataclass
class RegimeMapGenerator:
    """Generate regime maps for cyclic loading."""
    E: float = 210e9
    sigma_y: float = 355e6
    H: float = 1e9  # kinematic hardening modulus
    n_cycles_max: int = 100
    n_steps_per_cycle: int = 20

    def generate_map(self,
                     pressure_ratios: np.ndarray,
                     n_cycles_list: np.ndarray,
                     load_ratio: float = 0.0) -> np.ndarray:
        """Generate regime map.

        Parameters
        ----------
        pressure_ratios : array
            Pressure amplitude / yield pressure ratios
        n_cycles_list : array
            Number of cycles to simulate
        load_ratio : float
            R = p_min / p_max

        Returns
        -------
        regimes : 2D array of strings
            Shape (len(n_cycles_list), len(pressure_ratios))
        """
        regimes = np.empty((len(n_cycles_list), len(pressure_ratios)), dtype=object)

        for j, p_ratio in enumerate(pressure_ratios):
            # Convert pressure ratio to strain amplitude
            eps_y = self.sigma_y / self.E
            eps_amp = p_ratio * eps_y

            for i, n_cyc in enumerate(n_cycles_list):
                mat = KinematicHardening1D(
                    E=self.E, sigma_y0=self.sigma_y, H=self.H
                )
                history = run_cyclic_analysis(
                    mat, eps_amp, int(n_cyc),
                    load_ratio=load_ratio,
                    n_steps_per_cycle=self.n_steps_per_cycle
                )
                regimes[i, j] = classify_regime(history)

        return regimes

    def plot_map(self, pressure_ratios: np.ndarray,
                 n_cycles_list: np.ndarray,
                 regimes: np.ndarray,
                 title: str = "Cyclic Loading Regime Map",
                 figsize: Tuple[int, int] = (10, 7)) -> str:
        """Plot regime map and return base64-encoded PNG.

        Returns
        -------
        png_base64 : str
            Base64-encoded PNG image
        """
        fig, ax = plt.subplots(figsize=figsize)

        # Create colormap
        regime_names = list(REGIME_COLORS.keys())
        colors = [REGIME_COLORS[r] for r in regime_names]
        cmap = mcolors.ListedColormap(colors)

        # Map regimes to integers
        regime_int = np.zeros_like(regimes, dtype=int)
        for i, name in enumerate(regime_names):
            regime_int[regimes == name] = i

        # Plot
        X, Y = np.meshgrid(pressure_ratios, n_cycles_list)
        pcm = ax.pcolormesh(X, Y, regime_int, cmap=cmap, shading='auto',
                            vmin=-0.5, vmax=len(regime_names) - 0.5)

        ax.set_xlabel('Pressure Amplitude / Yield Pressure', fontsize=12)
        ax.set_ylabel('Number of Cycles', fontsize=12)
        ax.set_yscale('log')
        ax.set_title(title, fontsize=14)

        # Legend
        legend_elements = [
            plt.Rectangle((0, 0), 1, 1, facecolor=REGIME_COLORS[r],
                          label=REGIME_LABELS[r].replace('\n', ' '))
            for r in regime_names if r != "unknown"
        ]
        ax.legend(handles=legend_elements, loc='upper right', fontsize=10)

        # Add yield line
        ax.axvline(x=1.0, color='black', linestyle='--', alpha=0.5,
                    label='Yield boundary')
        ax.legend(handles=legend_elements + [ax.lines[-1]],
                  loc='upper right', fontsize=10)

        plt.tight_layout()

        # Save to base64
        buf = io.BytesIO()
        plt.savefig(buf, format='png', dpi=150, bbox_inches='tight')
        buf.seek(0)
        png_base64 = base64.b64encode(buf.read()).decode('utf-8')
        plt.close(fig)

        return png_base64


def generate_allowable_pressure_map(params: dict) -> dict:
    """Generate allowable pressure regime map for ice-belt plating.

    Parameters
    ----------
    params : dict
        Material and geometry parameters

    Returns
    -------
    result : dict
        Contains regime map data and base64 image
    """
    E = params.get("E", 210e9)
    sigma_y = params.get("sigma_y", 355e6)
    H = params.get("H", 1e9)

    # Pressure ratios from 0.1 to 3.0
    p_ratios = np.linspace(0.1, 3.0, 30)
    n_cycles = np.logspace(0, 4, 20).astype(int)  # 1 to 10000

    gen = RegimeMapGenerator(E=E, sigma_y=sigma_y, H=H)
    regimes = gen.generate_map(p_ratios, n_cycles, load_ratio=0.0)
    png_base64 = gen.plot_map(p_ratios, n_cycles, regimes,
                               title="Ice-Belt Plating: Cyclic Loading Regime Map")

    # Find allowable pressure (elastic shakedown boundary)
    allowable_ratio = None
    for j, p_ratio in enumerate(p_ratios):
        if regimes[0, j] != "elastic_shakedown":
            allowable_ratio = p_ratio
            break

    if allowable_ratio is None:
        allowable_ratio = p_ratios[-1]

    return {
        "pressure_ratios": p_ratios.tolist(),
        "n_cycles": n_cycles.tolist(),
        "regimes": regimes.tolist(),
        "png_base64": png_base64,
        "allowable_pressure_ratio": allowable_ratio,
        "allowable_pressure_Pa": allowable_ratio * sigma_y,
    }


def generate_regime_map_with_melan(params: dict) -> dict:
    """Generate regime map with Melan shakedown bound overlay.

    Combines incremental cyclic analysis with Melan LP bound.
    """
    E = params.get("E", 210e9)
    sigma_y = params.get("sigma_y", 355e6)
    H = params.get("H", 1e9)
    sec_b = params.get("sec_b", 0.6)
    sec_h = params.get("sec_h", 0.025)
    L = params.get("L", 2.4)

    sec = RectangularSection(b=sec_b, h=sec_h)
    mat_epp = EPPMaterial(E=E, sigma_y=sigma_y)

    beam = BeamStrip(L=L, b=sec_b, sec=sec, mat=mat_epp)
    p_yield = beam.pressure_at_first_yield()
    p_plastic = beam.pressure_at_full_plastic()

    # Melan shakedown
    melan = MelanShakedownBeam(sigma_y=sigma_y, E=E)
    M_amp = beam.Me  # use elastic moment as reference
    mu_sd = melan.shakedown_factor((-M_amp, M_amp))

    return {
        "p_yield_Pa": p_yield,
        "p_plastic_Pa": p_plastic,
        "melan_shakedown_factor": mu_sd,
        "p_melan_Pa": mu_sd * p_yield,
        "shape_factor": beam.Mp / beam.Me,
    }
