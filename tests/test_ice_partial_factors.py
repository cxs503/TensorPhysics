def test_gumbel_stability_property_is_exact() -> None:
    storm = GumbelParams(loc=1.0, scale=0.25)
    annual = storm_gumbel(storm, 12)
    assert annual.scale == pytest.approx(storm.scale, rel=1e-15)
    assert annual.loc == pytest.approx(1.0 + 0.25 * math.log(12.0), rel=1e-15)
    # the annual maximum is stochastically larger than a single storm peak,
    # hence its CDF is pointwise smaller
    assert annual.cdf(3.0) <= storm.cdf(3.0)
    assert annual.loc > storm.loc


def test_pressure_area_trend_matches_iso_power_law() -> None:
    assert TREND.mean_pressure(1.0) == pytest.approx(2.5)
    assert TREND.mean_pressure(4.0) == pytest.approx(2.5 * 4.0**-0.4)
    # monotone decreasing in area (ISO 19906 pressure-area law)
    values = [TREND.mean_pressure(a) for a in (1.0, 2.0, 5.0, 20.0)]
    assert all(a > b for a, b in zip(values, values[1:]))


def test_trend_fit_recovers_exponent() -> None:
    areas = [1.0, 2.5, 5.0, 10.0, 20.0]
    pressures = [TREND.mean_pressure(a) for a in areas]
    fit = fit_pressure_area_trend(areas, pressures)
    assert fit.exponent == pytest.approx(0.40, abs=1e-9)
    assert fit.p_ref == pytest.approx(2.5, rel=1e-9)
    assert fit.r_squared == pytest.approx(1.0, abs=1e-12)


def test_gumbel_moments_recovers_plant(plant: GumbelParams, ensemble: dict) -> None:
    fit = fit_gumbel_moments(ensemble[AREA])
    assert fit.loc == pytest.approx(plant.loc, rel=0.05)
    assert fit.scale == pytest.approx(plant.scale, rel=0.10)
    assert fit.cov() == pytest.approx(plant.cov(), rel=0.15)


def test_gumbel_mle_agrees_with_moments(plant: GumbelParams, ensemble: dict) -> None:
    mle = fit_gumbel_mle(ensemble[AREA])
    mom = fit_gumbel_moments(ensemble[AREA])
    assert mle.loc == pytest.approx(mom.loc, rel=0.05)
    assert mle.scale == pytest.approx(mom.scale, rel=0.08)
    # MLE cannot have a lower likelihood than the method of moments
    assert mle.log_likelihood >= mom.log_likelihood - 1e-9


def test_gumbel_mle_exact_for_quantile_sample() -> None:
    # Gumbel variates generated by the inverse CDF of a uniform grid give a
    # sample whose MLE must reproduce the generating parameters closely.
    params = GumbelParams(loc=2.0, scale=0.3)
    n = 400
    sample = [params.quantile((i + 0.5) / n) for i in range(n)]
    fit = fit_gumbel_mle(sample)
    assert fit.loc == pytest.approx(params.loc, abs=0.02)
    assert fit.scale == pytest.approx(params.scale, rel=0.02)


def test_gev_shape_is_gumbel_like_for_gumbel_data(ensemble: dict) -> None:
    gev = fit_gev_lmoments(ensemble[AREA])
    assert abs(gev.shape) < 0.15
    assert gev.scale > 0.0
    # GEV CDF must reproduce the Gumbel CDF in the shape -> 0 limit
    gumbel = fit_gumbel_mle(ensemble[AREA])
    x = gumbel.quantile(0.9)
    assert gev.cdf(x) == pytest.approx(math.exp(-math.exp(-(x - gumbel.loc) / gumbel.scale)), abs=0.12)


def test_gev_mle_dominates_lmoments(ensemble: dict) -> None:
    lmom = fit_gev_lmoments(ensemble[AREA])
    mle = fit_gev_mle(ensemble[AREA], start=lmom)
    assert mle.log_likelihood >= lmom.log_likelihood - 1e-9


def test_ks_statistic_small_for_plant(plant: GumbelParams, ensemble: dict) -> None:
    fit = fit_gumbel_mle(ensemble[AREA])
    assert ks_statistic_gumbel(ensemble[AREA], plant) < 0.12
    assert fit.ks_statistic < 0.12


