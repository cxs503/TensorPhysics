    panel = IceBeltPanel()
    result = calibrate_panel(panel, plant, samples_mc=0, samples_is=0).to_dict()
    assert result["beta_achieved"] == pytest.approx(4.0, abs=0.01)
    assert result["gamma_F"] * result["gamma_M"] == pytest.approx(result["k_star"], rel=1e-9)
