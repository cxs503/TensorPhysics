def test_problem_builds_a_usable_design_point(plant: GumbelParams) -> None:
    panel = IceBeltPanel()
    problem = build_problem(panel, plant)
    form = problem.form()
    assert form.converged
    assert form.beta > 0.0
    assert abs(form.g_design) < 1e-4
    assert len(form.alpha) == 5
    # the load-side variables dominate the design point (physical expectation)
    assert abs(form.alpha[0]) > abs(form.alpha[1])