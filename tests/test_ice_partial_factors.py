def test_load_effect_and_resistance_are_consistent() -> None:
    panel = IceBeltPanel()
    s = load_effect(panel, 1.0, panel.t_net_mm)
    assert s == pytest.approx(panel.alpha_b * (panel.b_mm / panel.t_net_mm) ** 2)
    assert load_effect(panel, 1.0, 0.0) == float("inf")
    assert load_effect(panel, 2.0, panel.t_net_mm) == pytest.approx(2.0 * s)


def test_characteristic_values_use_the_declared_quantiles(plant: GumbelParams) -> None:
    panel = IceBeltPanel()
    ch = characteristic_values(panel, plant)
    assert ch.p_exceedance_mpa == pytest.approx(plant.return_level(100.0))
    assert ch.s_k_mpa == pytest.approx(
        panel.alpha_b * plant.return_level(100.0) * (panel.b_mm / panel.t_net_mm) ** 2
    )
    assert ch.r_k_mpa < panel.fy_mean_mpa  # 5 % fractile below the mean
    assert ch.factor_product == pytest.approx(ch.r_k_mpa / ch.s_k_mpa)


def test_design_thickness_inversion_is_exact(plant: GumbelParams) -> None:
    panel = IceBeltPanel()
    ch = characteristic_values(panel, plant)
    k = 1.5
    t = design_thickness_for_factor(panel, ch, k)
    designed = panel.with_thickness(t)
    ch_designed = characteristic_values(designed, plant)
    # R_k = k * S_k(t_design) is the defining property of the format inversion
    assert ch_designed.s_k_mpa * k == pytest.approx(ch.r_k_mpa, rel=1e-12)


