def test_every_table_row_is_adjudicated(plant: GumbelParams) -> None:
    panel = IceBeltPanel()
    target_rows = adjudicate_target_reliability(4.0)
    factor_rows = adjudicate_factor_rows(1.5, 1.1)
    cases = adjudicate_design_cases(
        lambda product: achieved_beta_for_product(panel, plant, product)["beta_achieved"]
    )
    assert len(target_rows) == len(TARGET_RELIABILITY_ROWS)
    assert len(factor_rows) == len(LOAD_FACTOR_ROWS) + len(RESISTANCE_FACTOR_ROWS) + 2
    assert cases
    for row in target_rows + factor_rows + cases:
        assert "verdict" in row
        assert row["evidence_tier"] in {"conditional", "real"}
    summary = summarise_verdicts(target_rows + factor_rows + cases)
    assert summary["total_rows"] == len(target_rows) + len(factor_rows) + len(cases)
    assert summary["all_rows_verdicted"] is True


def test_provenance_of_iso_rows_is_declared() -> None:
    for row in TARGET_RELIABILITY_ROWS + LOAD_FACTOR_ROWS + RESISTANCE_FACTOR_ROWS:
        assert row.primary_source_verified is False
        assert row.source_tier == "secondary"
        assert row.basis  # every row carries its provenance text


