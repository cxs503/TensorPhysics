#!/usr/bin/env python3
"""Run the P82W4-N06 ice + wave combined fatigue study.

Writes ``artifacts/m7361/results.json`` (all criterion numbers, no hand-typed
value anywhere) plus a small ``criteria.md`` table for quick reading.

Usage::

    python3 scripts/ice_wave_fatigue_study.py [--quick] [--out DIR]
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Any, Dict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "src"))

from tensorphysics.ice_wave_fatigue.pipeline import run_study  # noqa: E402


def _md_table(summary: Dict[str, Any]) -> str:
    lines = [
        "# P82W4-N06 machine criteria (generated by scripts/ice_wave_fatigue_study.py)",
        "",
        "| id | criterion | measured | pass |",
        "|---|---|---|---|",
    ]
    a = summary["a"]
    lines.append(
        f"| (a) | linear superposition rho in [0.97,1.03] at f_ice/f_w>=10 | "
        f"in-band {a['measured_separated_in_band']}, branch={a['verdict_branch']}, "
        f"law max err {a['law_max_err_pct']:.2f} % (holdout {a['law_holdout_max_err_pct']:.2f} %), "
        f"sum-rule mean err {a['sum_rule_mean_err_pct']:.2f} % | {'PASS' if a['pass'] else 'FAIL'} |")
    b = summary["b"]
    lines.append(
        f"| (b) | Dirlik/TB error <= 10 % vs rainflow, three spectral widths | "
        f"Dirlik worst {b['worst_err_dirlik_pct']:.2f} %, TB worst {b['worst_err_tb_pct']:.2f} % "
        f"| {'PASS' if b['pass'] else 'FAIL'} |")
    c = summary["c"]
    sub = c["subchecks"]
    lines.append(
        f"| (c) | whipping caliber self-consistency <= 2 pp; slow-load share < 8 % | "
        f"A={sub['c3_A_measured_design']:.3f} vs peak-caliber {sub['c3_A_predicted_peak_caliber']:.3f} "
        f"({sub['c3_deviation_pp_design']:.1f} pp); harmonic slow share "
        f"{sub['c1_share_peak']:.3f}, pulse-train slow share {sub['c2_share_peak_stretched']:.3f} "
        f"| {'PASS' if c['pass'] else 'FAIL'} |")
    d = summary["d"]
    lines.append(
        f"| (d) | segmentation/closed-block permutation invariance <= 1e-9 | "
        f"seg {d['max_seg_rel_dev']:.3e}, perm {d['permutation_max_rel_dev']:.3e}, "
        f"naive-permutation spread {d['naive_permutation_spread_rel']:.3e} "
        f"| {'PASS' if d['pass'] else 'FAIL'} |")
    e = summary["e"]
    lines.append(
        f"| (e) | waves off reproduces m5528 within 2 % | "
        f"worst {e['worst_rel_err_pct']:.3e} % | {'PASS' if e['pass'] else 'FAIL'} |")
    lines.append("")
    lines.append(f"all_pass = **{summary['all_pass']}**")
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--quick", action="store_true", help="small/fast smoke configuration")
    ap.add_argument("--out", default=os.path.join(ROOT, "artifacts", "m7361"))
    args = ap.parse_args(argv)

    os.makedirs(args.out, exist_ok=True)
    result = run_study(quick=args.quick)
    path = os.path.join(args.out, "results_quick.json" if args.quick else "results.json")
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=1, ensure_ascii=False)
    md_path = os.path.join(args.out, "criteria.md")
    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write(_md_table(result["criteria_summary"]))
    print(f"wrote {path} ({os.path.getsize(path)} bytes) and {md_path}")
    for key, val in result["criteria_summary"].items():
        if key == "all_pass":
            continue
        print(f"  ({key}) pass={val['pass']}")
    print(f"  all_pass={result['criteria_summary']['all_pass']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())